export type Key = keyof typeof ja;
const dict: Record<Lang, Record<Key, string>> = { ja, en };

let lang: Lang = 'ja';
try {
  const s = localStorage.getItem('flytown.lang');
  if (s === 'ja' || s === 'en') lang = s;
} catch {
  /* 保存できない環境では既定のまま */
}

export function getLang(): Lang {
  return lang;
}

export function setLang(l: Lang): void {
  lang = l;
  try {
    localStorage.setItem('flytown.lang', l);
  } catch {
    /* 保存できない環境では次回に引き継がない */
  }
  if (typeof document !== 'undefined') document.documentElement.lang = l;
}

export function t(k: Key, p?: Record<string, string | number>): string {
  let s = dict[lang][k] ?? dict.ja[k] ?? k;
  if (p) for (const [a, b] of Object.entries(p)) s = s.split(`{${a}}`).join(String(b));
  return s;
}
